// Runs the Prisma CLI against PostgreSQL or the SQLite fallback, chosen by
// DATABASE_URL (default: file:./dev.db). Usage: node scripts/prisma.mjs <prisma args>
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import dotenv from "dotenv";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
dotenv.config({ path: path.join(root, ".env"), quiet: true });
process.env.DATABASE_URL ??= "file:./dev.db";

let schemaPath = path.join(root, "prisma", "schema.prisma");
if (process.env.DATABASE_URL.startsWith("file:")) {
  const sqliteDir = path.join(root, "prisma", "sqlite");
  mkdirSync(sqliteDir, { recursive: true });
  const source = readFileSync(schemaPath, "utf8").replace('provider = "postgresql"', 'provider = "sqlite"');
  schemaPath = path.join(sqliteDir, "schema.prisma");
  writeFileSync(schemaPath, `// GENERATED by scripts/prisma.mjs. Edit prisma/schema.prisma instead.\n${source}`);
  // SQLite paths resolve relative to the schema file; pin them to server/.
  const file = process.env.DATABASE_URL.slice("file:".length);
  if (!path.isAbsolute(file)) process.env.DATABASE_URL = `file:${path.join(root, file)}`;
}

const result = spawnSync("npx", ["prisma", ...process.argv.slice(2), "--schema", schemaPath], {
  stdio: "inherit",
  cwd: root,
  env: process.env,
});
process.exit(result.status ?? 1);
